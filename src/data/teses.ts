export function cnaeIn(cnae: string, grupo: keyof typeof CNAE_MAP): boolean {
  const clean = (cnae || "").replace(/\D/g, "");
  const c4 = clean.slice(0, 4);
  const c2 = clean.slice(0, 2);
  return CNAE_MAP[grupo].some((g) => {
    const gd = g.replace(/\D/g, "");
    return gd.length <= 2 ? c2 === gd : c4.startsWith(gd);
  });
}

